-- Marsoon-style personal trading journal schema (Supabase SQL Editor)
-- Run this SQL in your own Supabase project before connecting the website.
create table if not exists public.trades (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  trade_id text not null,
  trade_data jsonb not null,
  updated_at timestamptz not null default now(),
  unique(user_id, trade_id)
);

alter table public.trades enable row level security;

drop policy if exists "Users can read own trades" on public.trades;
create policy "Users can read own trades"
on public.trades for select to authenticated
using (auth.uid() = user_id);

drop policy if exists "Users can insert own trades" on public.trades;
create policy "Users can insert own trades"
on public.trades for insert to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Users can update own trades" on public.trades;
create policy "Users can update own trades"
on public.trades for update to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can delete own trades" on public.trades;
create policy "Users can delete own trades"
on public.trades for delete to authenticated
using (auth.uid() = user_id);

grant select, insert, update, delete on public.trades to authenticated;
